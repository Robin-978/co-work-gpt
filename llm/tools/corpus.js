// 重複幾次 + 用換行分隔，讓每個句型都被取樣到很多次。
//
// 段落跟單句混在一起排：段落內部保持相鄰（那是上下文要學的東西），
// 段落之間、以及段落跟單句之間空一行，讓「這裡是邊界」也是模型看得到的訊號。
// 單句每輪都洗牌一次順序，免得模型把「A 句後面一定接 B 句」也背下來——
// 那會讓它在段落裡也預期同樣的接續。段落內部當然不洗，順序就是要學的東西。
const REPEAT = 6;

function shuffled(list, seedInit) {
  const a = list.slice();
  let s = seedInit;
  const rnd = () => { s = (s * 1103515245 + 12345) & 0x7fffffff; return s / 0x7fffffff; };
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

function buildCorpus() {
  const parts = [];
  for (let r = 0; r < REPEAT; r++) {
    for (const p of PARAGRAPHS) { parts.push(p.join('\n')); parts.push(''); }
    for (const s of shuffled(SENTENCES, 20260813 + r)) parts.push(s);
    parts.push('');
  }
  return parts.join('\n') + '\n';
}

